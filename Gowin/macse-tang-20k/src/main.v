module main(


    output mac_hsync,
    output mac_vsync,
    output mac_active, // output for diagnostic
    output mac_pixel_clk, // output for diagnostic
    output reg video_out, // Changed to reg for procedural assignment

    // TTL RGB in
    // 2025 06 01 remapped entirely
    // 2025 07 20 only loading most significant bits of RGb 
    //input rgb_r0_E15, 
    //input rgb_r1_D14, 
    //input rgb_r2_A15, // using for HSYNC because N9 is dedicated to SSPI
    //input rgb_r3_B14, 
    input rgb_r_B14,

    //input rgb_g0_B13,
    //input rgb_g1_C12,
    //input rgb_g2_B12,
    //input rgb_g3_D10,
    input rgb_g_A14,
    // I don't know why Green has 6 bits and the others just get 5, 
    // but I'm dropping it anyway
    // needed the extra pin because I had to move 
    // Pixel Clock off of R9 because it overlapped with SSPI loading
    // // input rgb_g5_D10, 
    
    //input rgb_b0_P7,
    //input rgb_b1_B11,
    //input rgb_b2_A11,
    //input rgb_b3_D11,
    input rgb_b_b13,

    input rgb_odck, // PIXCLK
    input rgb_hsync, // Goes to A15
    input rgb_vsync,  // 
    input rgb_de,  // DISPEN on the Adafruit board schematic
    input rgb_active, // Active Video signal, not used currently

    // TODO: Map Active to an input so I can know if there is HDMI or not
    // TODO: Show the Mac Icon if no HDMI video

    // input rgb_bl, // Backlight control, not used
    // input tp_* // for the Touch Screen, Mac SE doesn't have one.


    // --- Switches and LEDs for test settings, not used currently ---
    input T5,  // Switch for Number5
//    input T4,  // Switch for Number4
//    input E8,  // Switch for Number3


    // output reg LED5_L16, 
    // output reg LED4_L14, 
    output RBG_CLOCK_LED3_N14,  // for incoming HDMI pixel clock divider
    output HDMI_ACTIVE_LED2_N16, // for incoming HDMI active

    // couple of outputs for the o'scope
    output oscope_T11,
    output oscope_P11,
    output oscope_T12,
    output oscope_R11,
    output oscope_M14,
    output oscope_M15,
    output oscope_J14,
    output oscope_J16
);

    // --- Clock Generation and Buffering for 15.xx MHz pixel clock ---
    // still not exactly right, but close enough
    // The clock is generated by the Gowin oscillator and then passed through a PLL
    // to get the right frequency for the Mac SE
    wire osc_clk_raw; // Raw oscillator output
    wire fifteen_clk; // Buffered clock for logic

    // get the clock, should be 125MHz (or 250MHz/2, see gowin_osc.v)
    Gowin_OSC u_osc_generator (
        .oscout(osc_clk_raw) // Connect oscillator output
    );

    // then do some fancy-dancy math with the PLL 
    // to get it to 15.6672MHz (but still not right)
    Gowin_rPLL mac_clock_pll(
        .clkout(fifteen_clk), // Buffered clock output
        .clkin(osc_clk_raw)   // Raw clock input
    );

    assign mac_pixel_clk = fifteen_clk;

    ///////////////////////////
    // FRAMEBUFFER BRAM SECTION
    ////////////////////////////
    // the BRAM is semi dual port, 
    // port A is write only to take data in from HDMI (TODO)
    // port B is read-only to read data from the framebuffer and output it to the screen
    // it is 175104 x 1, pass in the pixel counter to read.
    // Initialized with the Susan Kare original Mac icon.  [:^)]]

    // --- BRAM for Frame Buffer ---
    wire [17:0] ada, adb; // Address inputs
    wire din, dout;       // Data inputs/outputs
    wire clka, cea, reseta, clkb, ceb, resetb, oce; // Control signals

    Gowin_SDPB framebuffer(
        .dout(dout),
        .clka(clka),
        .cea(cea),
        .reseta(1'b0),
        .clkb(clkb),
        .ceb(ceb),
        .resetb(1'b0), // reset should always be low to enable it
        .oce(oce),
        .ada(ada),
        .din(din),
        .adb(adb)
    );

    //////////////////////////////////
    // --- Mac SE Timing Generator ---
    //////////////////////////////////
    wire [9:0] mac_x_coord;
    wire [8:0] mac_y_coord;
    wire [17:0] mac_pixel; // Pixel counter

    mac_se_timing_generator mac_timer(
        .clk(fifteen_clk),
        .hsync(mac_hsync),
        .vsync(mac_vsync),
        .active(mac_active),
        .pixel_x(mac_x_coord),
        .pixel_y(mac_y_coord),
        .pixel(mac_pixel)
    );

    // so now with every clock cycle the box should be spitting out perfect 
    // Mac SE VSYNC, and HSYNC signals, just like Woz used to make.
    // Internally, it's returning X & Y and total pixel count
    // to use to lookup black/white in the framebuffer
    // in the same time domain as the VSYNC and HSYNC


    // --- Mac CLock Time Domain Framebuffer Address and Clock Feeding ---
    // port B is read-only, port A is write-only
    assign clkb = fifteen_clk; // Use the pixel clock for framebuffer
    assign ceb = 1'b1;         // Enable framebuffer read
    assign adb = mac_pixel;    // Address is the pixel counter

    // Ensure BRAM output is valid
    assign oce = 1'b1;         // Output clock enable for BRAM

    // whenever the clock goes low, get the current pixel out of the framebuffer
    // and send it right out of the board i/o to make a beautiful picture
    always @(posedge fifteen_clk) begin
        video_out <= !(mac_active & dout); // Use AND condition for video_out
    end

    /////////////////////////////
    /////// HDMI DECODER SECTION //////////
    /////////////////////////////
    ////  start of GEMINI

        // --- Corrected Input Coordinate Generator ---
    // Assumes standard video timing: DE high for active pixels,
    // HSync/VSync pulses occur during blanking (DE low).
    // Assumes HSync and VSync are active-low pulses (adjust if needed).
    // --- Simplified Coordinate Generator + Registered BRAM Interface ---

    // Define active display dimensions
    localparam H_ACTIVE = 800;
    localparam V_ACTIVE = 480;

    // Define scaled output dimensions
    localparam H_CROP = 512;
    localparam V_CROP = 342;
    localparam BRAM_ADDR_WIDTH = $clog2(H_CROP * V_CROP); // 18 bits for 512x342

    // --- Input Signal Declarations (Example) ---
    // wire rgb_odck;
    // wire rgb_de, rgb_hsync, rgb_vsync;
    // wire rgb_r3_N7,...; // Example color bits

    // --- Internal Registers and Wires ---

    // Simplified Coordinate Generation Registers
    reg [9:0] input_x; // Input X coordinate (10 bits for H_ACTIVE)
    reg [8:0] input_y; // Input Y coordinate (9 bits for V_ACTIVE)
    reg input_coord_valid;
    reg rgb_hsync_prev;
    reg rgb_vsync_prev;
    reg rgb_de_prev;
    reg mono_pixel;
    reg input_y_debug;

    // changing from a bunch of lines of RGB to just the most significant bits
    // // Color Conversion Wires (faster than registers in an ALWAYS)
    // wire [7:0] red, green, blue;
    // assign red[0]   = 1'b0;; 
    // assign red[1]   = 1'b0;; 
    // assign red[2]   = 1'b0; // 0 bit (unused, but don't remember why)
    // assign red[3]   = 1'b0;; 
    // assign red[4]   = rgb_r4_A14; 
    // assign green[0] = rgb_g0_B13; 
    // assign green[1] = rgb_g1_C12; 
    // assign green[2] = rgb_g2_B12; 
    // assign green[3] = rgb_g3_D10; 
    // assign green[4] = rgb_g4_R7; 
    // // assign green[5] = rgb_g5_D10; // not loading this bit
    // assign blue[0]  = rgb_b0_P7; 
    // assign blue[1]  = rgb_b1_B11; 
    // assign blue[2]  = rgb_b2_A11; 
    // assign blue[3]  = rgb_b3_D11; 
    // assign blue[4]  = rgb_b4_N6; 

    // Sum the RGB wires
    // wire [8:0] rgb_sum = red + green + blue;

    // Remove scaler registers, use input_x/input_y directly
    // reg [8:0] scaled_write_x; // Scaled X coordinate (remove)
    // reg [8:0] scaled_write_y; // Scaled Y coordinate (remove)
    // reg scaled_mono_pixel;    // (remove)
    // reg scaled_write_enable;  // (remove)

    // *** BRAM Interface Registers (KEEP THESE) ***
    reg [17:0] bram_addr_reg; // BRAM address register (18 bits for 512x342)
    reg bram_din_reg;
    reg bram_ena_reg; // Port Enable register for BRAM
    reg bram_wea_reg; // Write Enable register for BRAM

    // Intermediate Wires
    // Detect falling edges (assuming active-low syncs)
    wire hsync_falling_edge = (rgb_hsync_prev == 1'b1 && rgb_hsync == 1'b0);
    wire vsync_falling_edge = (rgb_vsync_prev == 1'b1 && rgb_vsync == 1'b0);
    wire de_rising_edge   = (rgb_de_prev == 1'b0 && rgb_de == 1'b1);
    wire de_falling_edge  = (rgb_de_prev == 1'b1 && rgb_de == 1'b0);

    // Combinatorial calculation for next BRAM address
    wire [17:0] next_bram_addr = (input_y * H_CROP) + input_x;

    // --- Logic Implementation ---

    // --- Synchronize external video signals to rgb_odck domain ---
    reg rgb_de_sync_0, rgb_de_sync_1;
    reg rgb_hsync_sync_0, rgb_hsync_sync_1;
    reg rgb_vsync_sync_0, rgb_vsync_sync_1;

    always @(posedge rgb_odck) begin
        rgb_de_sync_0    <= rgb_de;
        rgb_de_sync_1    <= rgb_de_sync_0;
        rgb_hsync_sync_0 <= rgb_hsync;
        rgb_hsync_sync_1 <= rgb_hsync_sync_0;
        rgb_vsync_sync_0 <= rgb_vsync;
        rgb_vsync_sync_1 <= rgb_vsync_sync_0;
    end

    wire sync_rgb_de    = rgb_de_sync_1;
    wire sync_rgb_hsync = rgb_hsync_sync_1;
    wire sync_rgb_vsync = rgb_vsync_sync_1;

    // Edge detectors for synchronized signals
    reg sync_rgb_de_prev, sync_rgb_hsync_prev, sync_rgb_vsync_prev;
    always @(posedge rgb_odck) begin
        sync_rgb_de_prev    <= sync_rgb_de;
        sync_rgb_hsync_prev <= sync_rgb_hsync;
        sync_rgb_vsync_prev <= sync_rgb_vsync;
    end

    always @(posedge rgb_odck) begin
        // --- Latch Previous States ---
        rgb_hsync_prev <= rgb_hsync;
        rgb_vsync_prev <= rgb_vsync;
        rgb_de_prev    <= rgb_de;

        // --- Input Coordinate Generator for Cropping ---

        // Horizontal Counter (input_x)
        if (de_rising_edge) begin
            input_x <= 0;
        end else if (sync_rgb_de) begin
            input_x <= input_x + 1;
        end

        // Vertical Counter (input_y)
        if (vsync_falling_edge) begin
            input_y <= 0;
            input_y_debug <= 0;
        end else if (de_falling_edge) begin
            if (input_y < V_ACTIVE - 1) begin
                input_y <= input_y + 1;
                input_y_debug <= 1;
            end
        end

        // Coordinate Valid Signal - simply follows DE in this version
        input_coord_valid <= sync_rgb_de;

        // --- Color Converter ---
        if (input_coord_valid) begin
            mono_pixel <= rgb_r_B14 | rgb_g_A14 | rgb_b_b13;
        end else begin
            mono_pixel <= 1'b0;
        end

        // --- Cropping Logic ---
        if (input_coord_valid && (input_x < H_CROP) && (input_y < V_CROP)) begin
            bram_addr_reg <= (input_y * H_CROP) + input_x;
            bram_din_reg  <= mono_pixel;
            bram_ena_reg  <= 1'b1;
            bram_wea_reg  <= 1'b1;
        end else begin
            bram_ena_reg  <= 1'b0;
            bram_wea_reg  <= 1'b0;
        end
    end

    // --- BRAM Interface Assignments ---
    // Assign BRAM inputs directly from the dedicated registers
    // Ensure these port names match your BRAM primitive/inferred block

    assign clka = rgb_odck; // BRAM clock
    assign ada = bram_addr_reg; // Use registered address (assuming Port A)
    assign din = bram_din_reg;   // Use registered data (assuming Port A)
    assign cea = bram_ena_reg;    // Connect to Port A Enable (ENA)
    assign wea = bram_wea_reg;    // Connect to Port A Write Enable (WEA)
                                // Adjust based on your BRAM's data width and primitive.
        


    // debugging
    //assign P9 = input_y[3]; // Output for oscilloscope

    // ZO RELAXEN UND WATSCHEN DER BLINKENLICHTEN.

    // ACHTUNG! DAS INKOMMEN HDMI-SIGNAL IST NUN GE-AKTIVEN!
    assign HDMI_ACTIVE_LED2_N16 = ~rgb_active; // shine LED2 if HDMI is active


    // DEUGGER STUFF TO SEE IF THE RGB INPUTS ARE WORKING
    // --- rgb_odck activity indicator ---
    reg [23:0] rgb_odck_counter = 0;
    reg rgb_odck_blink = 0;
    always @(posedge rgb_odck) begin
        rgb_odck_counter <= rgb_odck_counter + 1;
        if (rgb_odck_counter == 24'd0) // overflow, about once per ~16M clocks
            rgb_odck_blink <= ~rgb_odck_blink;
    end

    // assign RBG_CLOCK_LED3_N14 = rgb_odck_blink && ~rgb_active; // Blink LED3 on RGB clock activity
    assign RBG_CLOCK_LED3_N14 = !(rgb_odck_blink && rgb_active); // Blink LED3 on RGB clock activity


    // oscilloscope debugging block
    assign oscope_P11 = rgb_de;             // Show DE signal
    assign oscope_T11 = input_x[0];         // Show input_x bit 0
    assign oscope_T12 = input_x[1];         // Show input_x bit 1
    assign oscope_R11 = input_y[0];         // Show input_y bit 0
    assign oscope_M14 = input_y[1];         // Show input_y bit 1
    assign oscope_M15 = rgb_de_prev;        // Show previous DE for edge debug
    assign oscope_J14 = de_rising_edge;     // Show DE rising edge for debug
    assign oscope_J16 = rgb_odck;           // Show pixel clock


endmodule
