// removing the external HDMI hardware and using the Gowin HDMI RX IP core

module main(


    output mac_hsync,
    output mac_vsync,
    output mac_active, // output for diagnostic
    output mac_pixel_clk, // output for diagnostic
    output reg video_out, // Changed to reg for procedural assignment

    // Universal reset (momentary push switch on T3 (Switch labeled 1))
    input rst, // Connect to FPGA pin T3
    // HDMI RX IP physical interface (to be connected to top-level or constraints)
    // (I_rst_n is now internal, see below)
    input I_tmds_clk_p, // HDMI_TXC_P (K14)
    input I_tmds_clk_n, // HDMI_TXC_N (K15)
    input [2:0] I_tmds_data_p, // [2]=G16, [1]=J15, [0]=H14
    input [2:0] I_tmds_data_n, // [2]=H15, [1]=K16, [0]=H16


    // --- Switches and LEDs for test settings, not used currently ---
    input T5  // Switch for Number5
//    input T4,  // Switch for Number4
//    input E8,  // Switch for Number3


    // output reg LED5_L16, 
    // output reg LED4_L14, 
    // output RBG_CLOCK_LED3_N14,  // for incoming HDMI pixel clock divider
    // output HDMI_ACTIVE_LED2_N16 // for incoming HDMI active

    // (oscope outputs removed to avoid pin conflicts)
);

    // --- Clock Generation and Buffering for 15.xx MHz pixel clock ---
    // still not exactly right, but close enough
    // The clock is generated by the Gowin oscillator and then passed through a PLL
    // to get the right frequency for the Mac SE
    wire osc_clk_raw; // Raw oscillator output
    wire fifteen_clk; // Buffered clock for logic

    // get the clock, should be 125MHz (or 250MHz/2, see gowin_osc.v)
    Gowin_OSC u_osc_generator (
        .oscout(osc_clk_raw) // Connect oscillator output
    );

    // then do some fancy-dancy math with the PLL 
    // to get it to 15.6672MHz (but still not right)
    Gowin_rPLL mac_clock_pll(
        .clkout(fifteen_clk), // Buffered clock output
        .clkin(osc_clk_raw)   // Raw clock input
    );

    assign mac_pixel_clk = fifteen_clk;

    ///////////////////////////
    // FRAMEBUFFER BRAM SECTION
    ////////////////////////////
    // the BRAM is semi dual port, 
    // port A is write only to take data in from HDMI (TODO)
    // port B is read-only to read data from the framebuffer and output it to the screen
    // it is 175104 x 1, pass in the pixel counter to read.
    // Initialized with the Susan Kare original Mac icon.  [:^)]]

    // --- BRAM for Frame Buffer ---
    wire [17:0] ada, adb; // Address inputs
    wire din, dout;       // Data inputs/outputs
    wire clka, cea, reseta, clkb, ceb, resetb, oce; // Control signals

    Gowin_SDPB framebuffer(
        .dout(dout),
        .clka(clka),
        .cea(cea),
        .reseta(rst),
        .clkb(clkb),
        .ceb(ceb),
        .resetb(rst), // use rst for both ports
        .oce(oce),
        .ada(ada),
        .din(din),
        .adb(adb)
    );

    //////////////////////////////////
    // --- Mac SE Timing Generator ---
    //////////////////////////////////
    wire [9:0] mac_x_coord;
    wire [8:0] mac_y_coord;
    wire [17:0] mac_pixel; // Pixel counter

    mac_se_timing_generator mac_timer(
        .clk(fifteen_clk),
        .hsync(mac_hsync),
        .vsync(mac_vsync),
        .active(mac_active),
        .pixel_x(mac_x_coord),
        .pixel_y(mac_y_coord),
        .pixel(mac_pixel)
    );

    // so now with every clock cycle the box should be spitting out perfect 
    // Mac SE VSYNC, and HSYNC signals, just like Woz used to make.
    // Internally, it's returning X & Y and total pixel count
    // to use to lookup black/white in the framebuffer
    // in the same time domain as the VSYNC and HSYNC


    // --- Mac CLock Time Domain Framebuffer Address and Clock Feeding ---
    // port B is read-only, port A is write-only
    assign clkb = fifteen_clk; // Use the pixel clock for framebuffer
    assign ceb = 1'b1;         // Enable framebuffer read
    assign adb = mac_pixel;    // Address is the pixel counter

    // Ensure BRAM output is valid
    assign oce = 1'b1;         // Output clock enable for BRAM

    // whenever the clock goes low, get the current pixel out of the framebuffer
    // and send it right out of the board i/o to make a beautiful picture
    always @(posedge fifteen_clk) begin
        video_out <= !(mac_active & dout); // Use AND condition for video_out
    end

    /////////////////////////////
    // HDMI RX IP INTEGRATION  //
    /////////////////////////////


    // TODO: Hook up these to the pins in the Dock specs
    // turn on HPD and DCC.  
    // hook clock up to some sort of clock.
    // resest to reset.

    // 600x600 EDID to tell the computer to do that resolution
	EDID_PROM_Top edid_prom(
		.I_clk(I_clk), //input I_clk
		.I_rst_n(I_rst_n), //input I_rst_n
		.I_scl(I_scl), //input I_scl
		.IO_sda(IO_sda) //inout IO_sda  
	);






    // Internal wires for DVI_RX_Top outputs
    wire O_pll_lock;
    wire [3:0] O_pll_phase;
    wire O_pll_phase_lock;
    wire O_rgb_clk;
    wire O_rgb_vs;
    wire O_rgb_hs;
    wire O_rgb_de;
    wire [7:0] O_rgb_r;
    wire [7:0] O_rgb_g;
    wire [7:0] O_rgb_b;

    // Instantiate the HDMI RX IP (internal clock version)
    DVI_RX_Top dvi_rx(
        .I_rst_n(~rst), // active-low reset
        .I_tmds_clk_p(I_tmds_clk_p),
        .I_tmds_clk_n(I_tmds_clk_n),
        .I_tmds_data_p(I_tmds_data_p),
        .I_tmds_data_n(I_tmds_data_n),
        .O_pll_lock(O_pll_lock),
        .O_pll_phase(O_pll_phase),
        .O_pll_phase_lock(O_pll_phase_lock),
        .O_rgb_clk(O_rgb_clk),
        .O_rgb_vs(O_rgb_vs),
        .O_rgb_hs(O_rgb_hs),
        .O_rgb_de(O_rgb_de),
        .O_rgb_r(O_rgb_r),
        .O_rgb_g(O_rgb_g),
        .O_rgb_b(O_rgb_b)
    );

    // Simple coordinate generator for framebuffer write (HDMI domain)
    reg [9:0] hdmi_x;
    reg [8:0] hdmi_y;
    reg O_rgb_de_prev;
    reg O_rgb_vs_prev;
    wire de_rising = (O_rgb_de_prev == 1'b0 && O_rgb_de == 1'b1);
    wire de_falling = (O_rgb_de_prev == 1'b1 && O_rgb_de == 1'b0);
    wire vs_falling = (O_rgb_vs_prev == 1'b1 && O_rgb_vs == 1'b0);

    always @(posedge O_rgb_clk) begin
        O_rgb_de_prev <= O_rgb_de;
        O_rgb_vs_prev <= O_rgb_vs;
        if (vs_falling) begin
            hdmi_y <= 0;
        end else if (de_falling) begin
            hdmi_y <= hdmi_y + 1;
        end
        if (de_rising) begin
            hdmi_x <= 0;
        end else if (O_rgb_de) begin
            hdmi_x <= hdmi_x + 1;
        end
    end

    // Monochrome conversion (simple OR of MSBs)
    wire mono_pixel = O_rgb_r[7] | O_rgb_g[7] | O_rgb_b[7];

    // Framebuffer write enable logic
    wire fb_write_en = O_rgb_de && (hdmi_x < 512) && (hdmi_y < 342);
    wire [17:0] fb_addr = (hdmi_y * 512) + hdmi_x;

    assign clka = O_rgb_clk;
    assign ada = fb_addr;
    assign din = mono_pixel;
    assign cea = fb_write_en;
    assign wea = fb_write_en;

    // HDMI activity LED (stub: always on if clock present)
    //assign HDMI_ACTIVE_LED2_N16 = O_rgb_clk;

    // (oscope assignments removed)

    // LED3 stub (no blink logic for now)
    //assign RBG_CLOCK_LED3_N14 = 1'b1;


endmodule
